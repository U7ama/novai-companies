// Attach singleton to globalThis in development so HMR does not wipe state mid-edit
const globalForCompanies = globalThis as unknown as {
  novaiCompaniesStore?: Company[];
};

export function getCompaniesStore(): Company[] {
  if (!globalForCompanies.novaiCompaniesStore) {
    globalForCompanies.novaiCompaniesStore = JSON.parse(
      JSON.stringify(INITIAL_COMPANIES)
    );
  }
  return globalForCompanies.novaiCompaniesStore!;
}

export function resetCompaniesStore(): void {
  globalForCompanies.novaiCompaniesStore = JSON.parse(
    JSON.stringify(INITIAL_COMPANIES)
  );
}

export function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

export function randomBetween(min: number, max: number): number {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

export async function simulateNetworkDelay(): Promise<void> {
  // In tests or CI, bypass or make delay minimal
  if (process.env.NODE_ENV === 'test' || process.env.VITEST) {
    return;
  }
  const delay = randomBetween(300, 800);
  await sleep(delay);
}
